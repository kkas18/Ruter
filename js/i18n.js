function fill(s,vars){return vars?s.replace(/\{(\w+)\}/g,(m,k)=>vars[k]!=null?String(vars[k]):m):s;}
function tr(s,vars){
  const e=I18N.lang==='en'?EN[s]:null;
  return fill(e==null?s:Array.isArray(e)?e[0]:e,vars);
}
// Entall og flertall: tn(n,'{n} bytte','{n} bytter').
function tn(n,one,many,vars){
  const e=I18N.lang==='en'?EN[one]:null;
  const s=Array.isArray(e)?e[n===1?0:1]:e!=null?e:n===1?one:many;
  return fill(s,{...vars,n});
}
const locale=()=>I18N.lang==='en'?'en-GB':'nb-NO';
// «Auto»: norsk når telefonen foretrekker norsk (eller svensk/dansk, som leser norsk greit) før
// engelsk, ellers engelsk.
function detectLang(langs=[]){
  const L=langs.map(l=>String(l).toLowerCase());
  const nb=L.findIndex(l=>/^(nb|nn|no|se)\b/.test(l)),en=L.findIndex(l=>/^en\b/.test(l));
  if(nb>=0&&(en<0||nb<en))return'nb';
  if(en>=0)return'en';
  return/^(sv|da)\b/.test(L[0]||'nb')||!L.length?'nb':'en';
}
function setLang(l){I18N.lang=l==='en'?'en':'nb';return I18N.lang;}

